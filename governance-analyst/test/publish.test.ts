import { mkdtemp, readFile, rm, stat } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { anchorDigest } from "../src/anchor.js";
import { analyseAction } from "../src/analyse.js";
import { splitConstitution } from "../src/constitution.js";
import { ingestOne } from "../src/ingest.js";
import { proposalListSchema } from "../src/koios.js";
import type { Completer } from "../src/model.js";
import { anchorUrl, hashFile, publish } from "../src/publish.js";
import { reviewAction } from "../src/review.js";
import { ActionStore, ConstitutionStore } from "../src/store.js";

const fixtures = path.join(import.meta.dirname, "fixtures");

describe("gov publish / gov anchor", () => {
  let dataDir: string;
  let govDir: string;
  let actions: ActionStore;
  const keys = [`${"1".repeat(64)}-0`, `${"2".repeat(64)}-0`];

  beforeEach(async () => {
    dataDir = await mkdtemp(path.join(os.tmpdir(), "gov-pub-"));
    govDir = await mkdtemp(path.join(os.tmpdir(), "gov-repo-"));
    actions = new ActionStore(dataDir);
    const list = proposalListSchema.parse(JSON.parse(await readFile(path.join(fixtures, "proposal_list.json"), "utf8")));
    const f = (async () => new Response(await readFile(path.join(fixtures, "anchors", "info-good.jsonld")))) as unknown as typeof fetch;
    await ingestOne(list[0], actions, { anchor: { fetch: f } });
    await ingestOne(list[1], actions, { anchor: { fetch: f } });
    const constitutions = new ConstitutionStore(dataDir);
    const text = await readFile(path.join(fixtures, "constitution-excerpt.md"));
    const ch = anchorDigest(text);
    await constitutions.save(ch, text, splitConstitution(text.toString("utf8")), {
      hash: ch, anchorUrl: "ipfs://x", actionKey: "k", proposalId: "g", enactedEpoch: 609, verifiedAt: "", bytes: 1, sections: 1, guardrails: 1,
    });
    const completer: Completer = {
      model: "fake",
      async complete() {
        return JSON.stringify({
          summary: "s", whatChangesIfPassed: "w", constitutionSections: [], tensions: [], budgetNotes: "", argumentsFor: ["a"], argumentsAgainst: ["b"], openQuestions: [],
          suggestedVote: { vote: "Abstain", confidence: 0.5, reason: "r" }, conflictOfInterest: { applies: false, reason: "" }, figures: [],
        });
      },
    };
    for (const k of keys) await analyseAction(k, actions, constitutions, { provenance: { agent: "alma:main:agent:test", almaVersion: "a".repeat(64) }, system: "s", completer, conflictOfInterestPolicy: "" });
    // Only the first one is decided.
    await reviewAction(keys[0], actions, { vote: "Abstain", reason: "conflict", decidedBy: { person: "Matías Falcone", role: "DRep" }, now: () => new Date("2026-11-04T03:00:00Z") });
  });
  afterEach(async () => {
    await rm(dataDir, { recursive: true, force: true });
    await rm(govDir, { recursive: true, force: true });
  });

  it("publishes decided actions only, with an index, and never touches undecided ones by default", async () => {
    const out = await publish(actions, { governanceDir: govDir });
    expect(out.map((o) => o.key)).toEqual([keys[0]]);
    expect(out[0].files).toEqual(["analysis.json", "analysis.md", "decision.json", "rationale.jsonld"]);
    await expect(stat(path.join(govDir, "votes", keys[1]))).rejects.toThrow();
    const index = await readFile(path.join(govDir, "votes", "README.md"), "utf8");
    expect(index).toContain("| 2026-11-04 | InfoAction |");
    expect(index).toContain("**Abstain**");
    expect(index).toContain("Generated by `gov publish`");

    const all = await publish(actions, { governanceDir: govDir, includeUndecided: true });
    expect(all).toHaveLength(2);
    expect((await readFile(path.join(govDir, "votes", "README.md"), "utf8")).split("\n").filter((l) => l.startsWith("| ")).length).toBe(4); // header, separator, 2 rows
  });

  it("gives the immutable anchor URL for a commit and re-checks the published bytes", async () => {
    await publish(actions, { governanceDir: govDir });
    const sha = "a".repeat(40);
    const served = await readFile(path.join(govDir, "votes", keys[0], "rationale.jsonld"));
    const f = (async (input: string | URL) => {
      expect(String(input)).toBe(`https://raw.githubusercontent.com/AdaSouls/cardano-governance/${sha}/votes/${keys[0]}/rationale.jsonld`);
      return new Response(served);
    }) as unknown as typeof fetch;
    const r = await anchorUrl(keys[0], actions, { branchOrCommit: sha, check: true, fetch: f });
    expect(r.check).toBe("verified");
    expect(r.expectedHash).toBe(await hashFile(path.join(govDir, "votes", keys[0], "rationale.jsonld")));

    const onMain = await anchorUrl(keys[0], actions, { branchOrCommit: "main" });
    expect(onMain.detail).toContain("not a commit sha");

    const tampered = (async () => new Response(Buffer.concat([served, Buffer.from("\n")]))) as unknown as typeof fetch;
    const bad = await anchorUrl(keys[0], actions, { branchOrCommit: sha, check: true, fetch: tampered });
    expect(bad.check).toBe("mismatch");
  });
});
